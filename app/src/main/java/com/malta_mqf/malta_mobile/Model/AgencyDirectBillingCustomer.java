package com.malta_mqf.malta_mobile.Model;

public class AgencyDirectBillingCustomer {

    private String agency_trn_no;
    private String customer_details;
    private String agency_billing_details;
    private String agency_id;
    private String agency_name;
    private String agency_code;

    // Getters and Setters

    public String getAgency_trn_no() {
        return agency_trn_no;
    }

    public void setAgency_trn_no(String agency_trn_no) {
        this.agency_trn_no = agency_trn_no;
    }

    public String getCustomer_details() {
        return customer_details;
    }

    public void setCustomer_details(String customer_details) {
        this.customer_details = customer_details;
    }

    public String getAgency_billing_details() {
        return agency_billing_details;
    }

    public void setAgency_billing_details(String agency_billing_details) {
        this.agency_billing_details = agency_billing_details;
    }

    public String getAgency_id() {
        return agency_id;
    }

    public void setAgency_id(String agency_id) {
        this.agency_id = agency_id;
    }

    public String getAgency_name() {
        return agency_name;
    }

    public void setAgency_name(String agency_name) {
        this.agency_name = agency_name;
    }

    public String getAgency_code() {
        return agency_code;
    }

    public void setAgency_code(String agency_code) {
        this.agency_code = agency_code;
    }
}
